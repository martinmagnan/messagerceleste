/** Renvoie la fonction de traduction d'une langue : t('cle', { n: 3 }). */
export const traducteur = (lang = 'fr') => (cle, vars = {}) => {
  const s = UI[lang]?.[cle] ?? UI.fr[cle] ?? cle;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
};
